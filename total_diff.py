def solution(arr):
    # # Brute force (On²)
    # total = 0
    # for i in range(len(arr)-1):
    #     for j in range(i, len(arr)):
    #         if abs(arr[j] - arr[i]) > 10:
    #             total += 1
        
    # return total
    
    # O(n.log(n))
    arr = sorted(arr)
    
    n = len(arr)
    
    total = 0
    for i in range(n-1):
        j = i + 1
        while j < n:
            if abs(arr[j] - arr[i]) > 10:
                break
            
            j += 1
        
        total += (n - j)
            
    return total



